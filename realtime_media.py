from __future__ import annotations

import asyncio
import hashlib
import itertools
import logging
import os
import subprocess
import tempfile
import threading
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from collections.abc import Sequence

import cv2
import numpy as np
from frame_store import VideoFrames, FrameSpool


@dataclass(frozen=True)
class _IdleMedia:
    frames: Sequence
    video: bytes


# Owned by the server process, not by a stream or its processor. Publish only
# complete results; the lock also prevents simultaneous starts rendering twice.
_INFERRED_IDLE_CACHE: dict[str, _IdleMedia] = {}
_INFERRED_IDLE_LOCK = threading.Lock()
logger = logging.getLogger("uvicorn.error")


def idle_dependency_signature(dependencies) -> tuple:
    """Check asset versions without resolving every individual filesystem path."""
    roots = tuple(str(Path(value).resolve()) for value in dependencies)
    stamps = {}
    extensions = {".jpg", ".png", ".lms", ".onnx"}

    def record(path, entry=None):
        try:
            stamp = entry.stat() if entry is not None else os.stat(path)
            stamps[path] = (stamp.st_mtime_ns, stamp.st_size)
        except FileNotFoundError:
            stamps[path] = None

    for root in roots:
        if not os.path.isdir(root):
            record(root)
            continue
        pending = [root]
        while pending:
            with os.scandir(pending.pop()) as entries:
                for entry in entries:
                    if entry.is_dir(follow_symlinks=False):
                        pending.append(entry.path)
                    elif os.path.splitext(entry.name)[1].lower() in extensions:
                        record(entry.path, entry)
    for name in ("realtime_media.py", "dihuman_run.py", "face_utils.py", "frame_store.py"):
        record(str(Path(__file__).resolve().with_name(name)))
    return roots, tuple(sorted(stamps.items()))


def read_inferred_idle_video(path: Path) -> bytes:
    """Serve generated idle from RAM, even if its disk copy was removed."""
    with _INFERRED_IDLE_LOCK:
        cached = _INFERRED_IDLE_CACHE.get(path.name)
        if cached is not None:
            return cached.video
    # The original-video fallback is not generated by silent inference.
    return path.read_bytes()


@dataclass(frozen=True)
class _SilentClip:
    signature: tuple[int, int, float]
    frames: Sequence
    size: tuple[int, int]


_SILENT_CLIP_CACHE: dict[Path, _SilentClip] = {}
_SILENT_CLIP_LOCK = threading.Lock()
_IDLE_MEDIA_CACHE: dict[str, _IdleMedia] = {}
_IDLE_MEDIA_LOCK = threading.Lock()


def load_silent_clip(source: Path, fps: float, *, cache: bool = True) -> _SilentClip:
    """Cache original idle pixels or open a bounded decoder for inferred idle."""
    source = source.resolve()
    fps = float(fps)
    with _SILENT_CLIP_LOCK:
        stamp = source.stat()
        signature = (stamp.st_mtime_ns, stamp.st_size, fps)
        cached = _SILENT_CLIP_CACHE.get(source) if cache else None
        if cached is not None and cached.signature == signature:
            return cached
        if not cache:
            frames = VideoFrames(source)
            if not np.isclose(frames.fps, fps, atol=0.01):
                frames.close()
                raise ValueError(f"silence.mp4 must use {fps:g} FPS, got {frames.fps:g}. Upload a matching clip.")
            logger.info("Silent clip opened for sequential decoding: %s frames=%s", source, len(frames))
            return _SilentClip(signature, frames, frames[0].shape[:2])
        images = []
        capture = cv2.VideoCapture(str(source))
        try:
            if not capture.isOpened():
                raise ValueError(f"Cannot read {source}. Upload a valid MP4 clip.")
            actual_fps = capture.get(cv2.CAP_PROP_FPS)
            if not np.isclose(actual_fps, fps, atol=0.01):
                raise ValueError(f"silence.mp4 must use {fps:g} FPS, got {actual_fps:g}. Upload a matching clip.")
            while True:
                ok, image = capture.read()
                if not ok:
                    break
                image.flags.writeable = False
                images.append(image)
        finally:
            capture.release()
        if len(images) < 2:
            raise ValueError(f"{source} has no usable loop. Upload a clip with at least two frames.")
        cached = _SilentClip(signature, tuple(images), images[0].shape[:2])
        if cache:
            _SILENT_CLIP_CACHE[source] = cached
        logger.info("Silent clip %s: %s frames=%s (original pixels)",
                    "cached" if cache else "decoded", source, len(images))
        return cached


def read_idle_video(path: Path) -> bytes:
    """Serve cached idle video from RAM even if the disk copy was removed."""
    with _IDLE_MEDIA_LOCK:
        cached = _IDLE_MEDIA_CACHE.get(path.name)
        if cached is not None:
            return cached.video
    return read_inferred_idle_video(path)


def prepare_idle_loop(source: Path, frames: int, fps: float, cache_dir: Path, *, output_size=None) -> Path:
    """Cache original silence.mp4 frames and a lossless RGB ping-pong WebM."""
    with _IDLE_MEDIA_LOCK:
        clip = load_silent_clip(source, fps)
        if frames != len(clip.frames):
            raise ValueError("Silent clip frame count does not match the avatar.")
        identity = repr((str(source.resolve()), clip.signature, frames, output_size, "source-rgb-v5"))
        key = hashlib.sha256(identity.encode()).hexdigest()[:24]
        cache_dir.mkdir(parents=True, exist_ok=True)
        output = cache_dir / f"idle-{key}.webm"
        cached = _IDLE_MEDIA_CACHE.get(output.name)
        if cached is not None:
            if not output.is_file():
                output.write_bytes(cached.video)
            return output
        images = clip.frames
        if output_size is not None:
            images = tuple(cv2.resize(image, tuple(map(int, output_size)), interpolation=cv2.INTER_LINEAR) for image in images)
            for image in images:
                image.flags.writeable = False
        if output.is_file() and output.stat().st_size:
            _IDLE_MEDIA_CACHE[output.name] = _IdleMedia(images, output.read_bytes())
            return output
        temporary = cache_dir / f"idle-{key}-{uuid.uuid4().hex}.webm"
        started = time.perf_counter()
        try:
            _encode_idle_frames(images, fps, temporary)
            temporary.replace(output)
            video = output.read_bytes()
        except FileNotFoundError as exc:
            raise RuntimeError("Local idle playback requires ffmpeg with the libvpx-vp9 encoder.") from exc
        finally:
            temporary.unlink(missing_ok=True)
        _IDLE_MEDIA_CACHE[output.name] = _IdleMedia(images, video)
        logger.info("Original idle WebM cached in %.2fs: %s bytes", time.perf_counter() - started, len(video))
        return output


def prepare_inferred_idle_loop(processor, fps: float, cache_dir: Path, *, dependencies=(), offline_quality=True,
                               source_frames=None, initialize_models=None) -> Path:
    """Reuse silent inference frames and RGB video for the server's lifetime."""
    with _INFERRED_IDLE_LOCK:
        return _prepare_inferred_idle_loop(
            processor, fps, cache_dir, dependencies=dependencies, offline_quality=offline_quality,
            source_frames=source_frames,
            initialize_models=initialize_models,
        )


def _prepare_inferred_idle_loop(processor, fps: float, cache_dir: Path, *, dependencies, offline_quality, source_frames,
                                initialize_models=None) -> Path:
    from dihuman_run import SAMPLE_RATE

    images = processor.full_body_img_list if source_frames is None else source_frames
    frames = len(images)
    if frames != len(processor.full_body_img_list):
        raise ValueError("Idle source must match the avatar frame count.")
    if frames < 2:
        raise ValueError("Inferred idle requires at least two avatar frames.")
    dependencies = tuple(dependencies)
    signature = idle_dependency_signature(dependencies)
    # Callers without asset paths can still have distinct in-memory avatars.
    image_identity = None if dependencies else [
        hashlib.sha256(image.tobytes()).hexdigest() for image in images
    ]
    identity = repr(("silent-inference-rgb-v3", float(fps), frames, images[0].shape,
                     processor.bbox_list, offline_quality, source_frames is not None, signature, image_identity))
    key = hashlib.sha256(identity.encode()).hexdigest()[:24]
    cache_dir.mkdir(parents=True, exist_ok=True)
    output = cache_dir / f"idle-inferred-{key}.webm"
    cached = _INFERRED_IDLE_CACHE.get(output.name)
    if cached is not None:
        logger.info("Idle cache hit: pid=%s frames=%s video_bytes=%s", os.getpid(), frames, len(cached.video))
        if not output.is_file():
            output.write_bytes(cached.video)
        return output
    if output.is_file():
        # The key includes source/model versions. Restore the forward leg of
        # the lossless loop after a process restart without repeating inference.
        restored = None
        try:
            restored = VideoFrames(output, frame_count=frames)
            if restored[0].shape != images[0].shape or restored[frames - 1].shape != images[0].shape:
                raise ValueError("Cached idle dimensions do not match the source.")
        except (ValueError, RuntimeError):
            if restored is not None:
                restored.close()
            restored = None
        if restored is not None:
            restored.close()  # Reopen lazily if decoded frames are requested.
            video = output.read_bytes()
            _INFERRED_IDLE_CACHE[output.name] = _IdleMedia(restored, video)
            logger.info("Inferred idle disk cache hit: frames=%s video_bytes=%s", frames, len(video))
            return output
    if initialize_models is not None:
        initialize_models()
        # Export may have created/updated ONNX assets. Publish under their final
        # signature so the next user or server restart finds the same file.
        return _prepare_inferred_idle_loop(
            processor, fps, cache_dir, dependencies=dependencies, offline_quality=offline_quality,
            source_frames=source_frames,
        )
    temporary = cache_dir / f"idle-inferred-{key}-{uuid.uuid4().hex}.webm"
    picker = processor.frame_picker
    cursor = picker.index, picker.step, processor.last_frame_index
    audio_history = processor.feather_audio_buffer
    samples = round(SAMPLE_RATE / fps)
    silence = np.zeros(frames * samples, np.int16)
    inferred_frames = FrameSpool(cache_dir, images[0].shape)
    original_images = processor.full_body_img_list
    # Static CPU/GPU image inputs are indexed by frame number. Inputs from the
    # training video must never be reused while rendering silence.mp4 pixels.
    image_caches = {name: getattr(processor, name) for name in
                    ("_realtime_input_cache", "_realtime_gpu_inputs") if hasattr(processor, name)}
    try:
        if source_frames is not None:
            processor.full_body_img_list = images
            for name in image_caches:
                delattr(processor, name)
        started = time.perf_counter()
        logger.info("Idle cache miss: preparing silent features for %s frames", frames)
        windows = (processor.prepare_offline_features(silence) if offline_quality
                   else processor.prepare_realtime_features(silence, frames))
        logger.info("Idle silent features ready in %.2fs", time.perf_counter() - started)
        started = time.perf_counter()
        for index in range(frames):
            picker.index, picker.step = index, 1
            image = processor.process_realtime(silence[:samples], windows[index])
            inferred_frames.append(image)
            if (index + 1) % 100 == 0:
                logger.info("Idle rendering: %s/%s frames, %.2fs", index + 1, frames, time.perf_counter() - started)
        logger.info("Idle frames rendered in %.2fs", time.perf_counter() - started)
        started = time.perf_counter()
        _encode_inferred_idle_frames(inferred_frames, fps, temporary)
        temporary.replace(output)
        video = output.read_bytes()
        logger.info("Idle WebM encoded in %.2fs: %s bytes", time.perf_counter() - started, len(video))
    except FileNotFoundError as exc:
        inferred_frames.close()
        raise RuntimeError("Inferred idle playback requires ffmpeg with the libvpx-vp9 encoder.") from exc
    except BaseException:
        inferred_frames.close()
        raise
    finally:
        processor.full_body_img_list = original_images
        if source_frames is not None:
            for name in ("_realtime_input_cache", "_realtime_gpu_inputs"):
                if hasattr(processor, name):
                    delattr(processor, name)
                if name in image_caches:
                    setattr(processor, name, image_caches[name])
        picker.index, picker.step, processor.last_frame_index = cursor
        processor.feather_audio_buffer = audio_history
        temporary.unlink(missing_ok=True)
    _INFERRED_IDLE_CACHE[output.name] = _IdleMedia(inferred_frames, video)
    return output


def _encode_inferred_idle_frames(images, fps: float, output: Path) -> None:
    _encode_idle_frames(images, fps, output)


def _encode_idle_frames(images, fps: float, output: Path) -> None:
    """Pipe raw BGR directly to ffmpeg, avoiding PNG encode/decode and disk IO."""
    height, width = images[0].shape[:2]
    # Supply the backward leg from cached frames. ffmpeg's reverse filter would
    # buffer another entire native-resolution loop, potentially several GB.
    loop = itertools.chain(images, (images[index] for index in range(len(images) - 2, 0, -1)))
    # A file for stderr prevents a full pipe deadlocking while stdin is written.
    with tempfile.TemporaryFile() as errors:
        with subprocess.Popen([
            "ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
            "-f", "rawvideo", "-pixel_format", "bgr24", "-video_size", f"{width}x{height}",
            "-framerate", str(fps), "-i", "pipe:0",
            "-map", "0:v", "-an",
            "-c:v", "libvpx-vp9", "-lossless", "1", "-pix_fmt", "gbrp",
            "-colorspace", "rgb", "-color_range", "pc",
            "-deadline", "realtime", "-cpu-used", "8", "-row-mt", "1",
            "-threads", "4", "-g", str(round(fps)), "-r", str(fps), str(output),
        ], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=errors) as encoder:
            try:
                try:
                    for image in loop:
                        encoder.stdin.write(image.tobytes())
                    encoder.stdin.close()
                except BrokenPipeError:
                    # Read ffmpeg's own failure below instead of hiding it.
                    pass
                if encoder.wait():
                    errors.seek(0)
                    raise RuntimeError(f"Cannot prepare inferred idle video: {errors.read().decode(errors='replace')[-2000:]}")
            except BaseException:
                if encoder.poll() is None:
                    encoder.kill()
                    encoder.wait()
                raise


class SpeechProducer:
    """One owner of model state; rendering runs ahead without blocking delivery."""

    def __init__(self, stream: Any, capacity: int = 24, select_cursor=None, render_packets=None):
        self.stream = stream
        self.select_cursor = select_cursor
        self.render_packets = render_packets or stream.next_patch_packets
        self.queue: asyncio.Queue = asyncio.Queue(maxsize=capacity)
        self.task: asyncio.Task | None = None
        self.error: Exception | None = None
        self._closing = False
        self._job: asyncio.Task | None = None
        self._needs_cursor = True
        self._generation = stream.audio_generation

    def start(self) -> None:
        self.task = asyncio.create_task(self._run())

    async def _in_thread(self, function, *args, **kwargs):
        self._job = asyncio.create_task(asyncio.to_thread(function, *args, **kwargs))
        try:
            return await asyncio.shield(self._job)
        finally:
            # Cancellation cannot stop a GPU call. Drain it before releasing its owner.
            if not self._job.done():
                await self._job
            self._job = None

    async def _run(self) -> None:
        try:
            while not self._closing:
                if self._generation != self.stream.audio_generation:
                    self._generation = self.stream.audio_generation
                    self._needs_cursor = True
                    self._reservation = None
                # Backpressure applies before rendering, including one in-flight frame.
                if self.queue.full():
                    await asyncio.sleep(0.005)
                    continue
                await self._in_thread(self.stream.prepare_audio)
                if not self.stream.has_prepared_audio():
                    await asyncio.sleep(0.01)
                    continue
                if self._needs_cursor:
                    reservation = None
                    if getattr(self.stream, "local_idle", False) and self.select_cursor:
                        generation = self.stream.audio_generation
                        reservation = await self.select_cursor(generation)
                        if reservation is None or generation != self.stream.audio_generation or not self.stream.has_prepared_audio():
                            continue
                        picker = self.stream.processor.frame_picker
                        picker.index, picker.step = reservation["frame_index"], reservation["direction"]
                    self._reservation = reservation
                    self._needs_cursor = False
                count = min(self.queue.maxsize - self.queue.qsize(), getattr(self.stream, "render_batch_frames", 1))
                packets = await self._in_thread(self.render_packets, count, prepare=False)
                if packets and getattr(self, "_reservation", None):
                    packets[0]["playback_start"] = self._reservation["playback_start"]
                    self._reservation = None
                for packet in packets:
                    if packet["generation"] == self.stream.audio_generation:
                        await self.queue.put(packet)
                        if packet["utterance_end"]:
                            self._needs_cursor = True
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            self.error = exc

    async def get(self) -> dict:
        while True:
            if self.error:
                raise self.error
            try:
                packet = await asyncio.wait_for(self.queue.get(), 0.05)
            except asyncio.TimeoutError:
                if self._closing:
                    raise asyncio.CancelledError()
                continue
            if packet["generation"] == self.stream.audio_generation:
                return packet

    def discard_stale(self) -> None:
        # Called on the same event loop as the producer and its consumer.
        retained = []
        while not self.queue.empty():
            packet = self.queue.get_nowait()
            if packet["generation"] == self.stream.audio_generation:
                retained.append(packet)
        for packet in retained:
            self.queue.put_nowait(packet)

    async def close(self) -> None:
        self._closing = True
        if self.task:
            self.task.cancel()
            await asyncio.gather(self.task, return_exceptions=True)
